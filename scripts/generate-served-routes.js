#!/usr/bin/env node
// Writes src/mocks/served-routes.ts from the backend's published contract.
//
// Every operation the deployment serves goes to the deployment, in every build,
// and never to a mock. Until 6 Oct 2026 development and preview builds answered
// up to 395 of the 978 served operations from fixtures, which hid working
// features (events, reminders, the notification inbox) behind canned data.
//
// Run after the backend contract changes:
//   node scripts/generate-served-routes.js [path/to/Diaspora.Api.json]
// `served-routes-drift.test.ts` fails when the file and the contract disagree.

const fs = require('fs');
const path = require('path');

const contractPath =
  process.argv[2] ??
  path.join(__dirname, '..', '..', 'diaspora-backend', 'contracts', 'Diaspora.Api.json');
const outPath = path.join(__dirname, '..', 'src', 'mocks', 'served-routes.ts');

const VERBS = ['get', 'post', 'put', 'patch', 'delete'];

function servedRoutes(contract) {
  const rows = [];
  for (const [route, operations] of Object.entries(contract.paths)) {
    if (!route.startsWith('/api/v1/')) continue;
    const pathOnly = route.slice('/api/v1'.length);
    for (const verb of Object.keys(operations)) {
      if (VERBS.includes(verb.toLowerCase())) rows.push([verb.toLowerCase(), pathOnly]);
    }
  }
  rows.sort((a, b) => (a[1] === b[1] ? a[0].localeCompare(b[0]) : a[1].localeCompare(b[1])));
  return rows;
}

function render(rows) {
  const lines = rows.map(([verb, route]) => `  ['${verb}', '${route}'],`);
  return `// GENERATED by scripts/generate-served-routes.js from the backend's
// contracts/Diaspora.Api.json. Do not edit by hand; run the script.
//
// Every operation the deployment serves, as [verb, path without /api/v1].
// \`initMocks\` passes these through to the network before any mock is
// registered, so no build answers a served route from a fixture.

export const SERVED_ROUTES: readonly (readonly ['get' | 'post' | 'put' | 'patch' | 'delete', string])[] = [
${lines.join('\n')}
];
`;
}

if (require.main === module) {
  const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
  const rows = servedRoutes(contract);
  fs.writeFileSync(outPath, render(rows));
  console.log(`wrote ${rows.length} served operations to ${path.relative(process.cwd(), outPath)}`);
}

module.exports = { servedRoutes, render };
