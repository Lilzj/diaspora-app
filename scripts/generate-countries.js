#!/usr/bin/env node
// Writes src/lib/reference/countries.ts from the backend's country table.
//
// The Location module owns the country catalogue: it serves
// `GET /api/v1/location/countries`, and registration eligibility is decided on
// the server. This file is the client's copy of that table, and it is a copy
// because the three screens that need it most — `choose-country`,
// `choose-origin` and `eligibility-error` — run before the member has a token,
// and every route in the Location module carries
// `.RequireAuthorization(LocationPolicies.ReadCatalog)`. There is no
// `AllowAnonymous` in the module, and the integration suite asserts that an
// anonymous caller gets 401. So the registration funnel cannot fetch the
// catalogue, and a bundled list is not a fallback there — it is the only
// source.
//
// Generating it is therefore the whole of the mechanism: one authored table,
// one derived copy, and `countries-drift.test.ts` to fail when they disagree.
//
// Run after the backend's table changes:
//   node scripts/generate-countries.js [path/to/diaspora-backend]
//
// The backend is located the way the drift suites locate it: an explicit
// argument, else `DIASPORA_BACKEND_PATH`, else the sibling checkout. A named
// path that does not resolve is a misconfigured run and throws rather than
// falling back, for the reason `support/backend-checkout.ts` gives at length.

const fs = require('fs');
const path = require('path');

const TABLE = path.join(
  'src',
  'Diaspora.Modules.Location',
  'Persistence',
  'Seeding',
  'WorldCountryData.cs'
);

// `new("AF", "Afghanistan", "+93")`. Names carry `&`, `-` and an apostrophe
// (`Côte d'Ivoire`), none of which need escaping inside a C# double-quoted
// literal, so a non-greedy run of non-quote characters is the whole grammar.
const RECORD = /new\("([A-Z]{2})",\s*"([^"]+)",\s*"(\+\d+)"\)/g;

/**
 * Every `new(...)` in the file, counted without parsing it.
 *
 * The two numbers are compared because a regex that silently matches fewer
 * rows than the file holds is the failure this whole mechanism exists to
 * prevent, one level down: a generator that drops a country writes a shorter
 * list, the drift test compares that list against the same dropped parse, and
 * both agree. Counting the raw occurrences is the only part of this script
 * that does not share the parser's assumptions.
 */
function recordCount(source) {
  return (source.match(/new\(/g) ?? []).length;
}

/**
 * The backend's table, in the backend's order.
 *
 * @throws when the parse recovers fewer records than the file contains.
 */
function parseCountryTable(source) {
  const rows = [];
  let match;

  RECORD.lastIndex = 0;
  while ((match = RECORD.exec(source)) !== null) {
    rows.push({ code: match[1], name: match[2], callingCode: match[3] });
  }

  const present = recordCount(source);
  if (rows.length !== present) {
    throw new Error(
      `WorldCountryData.cs holds ${present} records and the parser recovered ${rows.length}. ` +
        'A record is spelled in a way this script does not read — fix the pattern rather than ' +
        'the table, because a short parse here is written out as a short country list and the ' +
        'drift test would compare that list against the same short parse and agree.'
    );
  }

  if (rows.length === 0) {
    throw new Error(`No country records found in ${TABLE}. Refusing to write an empty list.`);
  }

  return rows;
}

/**
 * The flag for an ISO 3166-1 alpha-2 code.
 *
 * Unicode encodes every one of them as the pair of REGIONAL INDICATOR SYMBOLs
 * for its two letters (U+1F1E6 is A), so this is the rule rather than a lookup
 * table with its own drift problem — which is why the backend's table does not
 * carry a flag column and does not need one. Verified against all 191 entries
 * of the hand-written list this replaced: every flag was already exactly this.
 */
function flagFor(code) {
  return [...code].map((letter) => String.fromCodePoint(0x1f1e6 + letter.charCodeAt(0) - 65)).join('');
}

/** Single quotes, except where the name carries an apostrophe and they would need escaping. */
function quote(value) {
  return value.includes("'") ? `"${value}"` : `'${value}'`;
}

function render(rows) {
  const entries = rows
    .map(
      (row) =>
        `  { code: '${row.code}', name: ${quote(row.name)}, flag: '${flagFor(row.code)}', ` +
        `callingCode: '${row.callingCode}' },`
    )
    .join('\n');

  return `// GENERATED by scripts/generate-countries.js from the backend's
// ${TABLE.split(path.sep).join('/')}.
// Do not edit by hand: edit the backend's table and run the script.
//
// ── Why there are two copies, and why this one is derived ───────────────────
//
// The Location module owns the catalogue. It serves
// \`GET /api/v1/location/countries\`, and the server decides registration
// eligibility. The audit's preferred end state was for the client to fetch the
// list at runtime and keep a bundled copy only as an offline fallback
// (FSOLID-008 step 2, option 1). That is not available to the screens the
// finding is about: \`choose-country\`, \`choose-origin\` and
// \`eligibility-error\` run before the member has a token, every Location route
// carries \`.RequireAuthorization(LocationPolicies.ReadCatalog)\`, there is no
// \`AllowAnonymous\` in the module, and \`LocationModuleTests\` asserts that an
// anonymous caller is refused. On the registration funnel a bundled list is not
// a fallback — it is the only source.
//
// So the copy stays and the mechanism is that it is **derived**. One table is
// authored, in the backend; this file is written from it; and
// \`src/lib/__tests__/countries-drift.test.ts\` fails when the two disagree.
// That suite runs in the \`contract-drift\` CI job, which checks out the
// backend — a cross-repository check that does not run has not passed
// (FBL-001).
//
// The flag is not stored on either side. Unicode encodes every alpha-2 code as
// its pair of regional indicator symbols, so it is computed from the code.
//
// Until 18 Nov 2026 this list lived in \`src/mocks/countries.ts\` and was
// imported from there by fifteen production files (FBL-002). The rule that
// keeps production code out of \`src/mocks\` is in
// \`src/lib/__tests__/production-bundle-shape.test.ts\`.

export interface CountryItem {
  code: string;
  name: string;
  flag: string;
  callingCode: string;
}

export const allCountries: CountryItem[] = [
${entries}
];
`;
}

/**
 * The backend checkout, by the same rule the drift suites use: a named path
 * that does not resolve is a misconfigured run, not a developer without the
 * sibling repository.
 */
function backendRoot(explicit) {
  const named = explicit ?? process.env.DIASPORA_BACKEND_PATH;

  if (named !== undefined && named !== '') {
    if (!fs.existsSync(path.join(named, 'src'))) {
      throw new Error(
        `"${named}" is not a backend checkout (no "src" directory inside it). A named path ` +
          'that does not resolve is a misconfigured run, so this fails rather than falling ' +
          'back to the sibling checkout.'
      );
    }
    return named;
  }

  return path.join(__dirname, '..', '..', 'diaspora-backend');
}

if (require.main === module) {
  const root = backendRoot(process.argv[2]);
  const source = fs.readFileSync(path.join(root, TABLE), 'utf8');
  const rows = parseCountryTable(source);
  const outPath = path.join(__dirname, '..', 'src', 'lib', 'reference', 'countries.ts');

  fs.writeFileSync(outPath, render(rows));
  console.log(`wrote ${rows.length} countries to ${path.relative(process.cwd(), outPath)}`);
}

module.exports = { parseCountryTable, flagFor, render, backendRoot, TABLE };
