/**
 * Expo config plugin — permit cleartext HTTP to loopback addresses only.
 *
 * ── Why this exists ──────────────────────────────────────────────────────────
 *
 * Runtime validation has to run against a *release* build. A debug build sets
 * `__DEV__`, which makes `areSimulatedFeaturesEnabled()` true, which bolts a
 * `MockAdapter` onto the real `apiClient` — auth, housing, marketplace, jobs and
 * community life are then served from fixtures. Validating that build would
 * validate the fixtures.
 *
 * But a release build refuses cleartext, so it cannot reach a locally running
 * `Diaspora.Api` over http. This plugin opens exactly the addresses that only
 * ever mean "the machine this device is attached to":
 *
 *     10.0.2.2                the Android emulator's alias for the host loopback
 *     127.0.0.1 / localhost   the device's own loopback, used with `adb reverse`
 *
 * Neither is routable to anything on a real device, so this does not widen what a
 * shipped build can reach. Every real host the application talks to remains
 * cleartext-refused by the platform default.
 *
 * ── Why a plugin rather than editing android/ ────────────────────────────────
 *
 * `android/` is a generated folder and is gitignored. A hand-edited
 * `AndroidManifest.xml` and `res/xml/network_security_config.xml` are lost on
 * the next `expo prebuild` and absent from a fresh clone — which would make the
 * runtime evidence unreproducible by anybody else. Expressed here, it is
 * regenerated every time.
 *
 * ── Why not `usesCleartextTraffic` ───────────────────────────────────────────
 *
 * `expo-build-properties` can set `usesCleartextTraffic: true`, which is one
 * line and permits cleartext to *every* host. This is deliberately narrower: a
 * build that can talk to a local server is useful, and a build that can talk to
 * any server in plaintext is a different thing entirely.
 */
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const CONFIG_FILE = 'network_security_config.xml';

const CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-loopback-cleartext.js — do not edit by hand.
  Cleartext is refused everywhere except the loopback aliases below, which are
  not routable to anything on a real device.
-->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">10.0.2.2</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
`;

/** Writes the XML into the generated res/xml directory. */
const withConfigFile = (config) =>
  withDangerousMod(config, [
    'android',
    async (cfg) => {
      const target = path.join(
        cfg.modRequest.platformProjectRoot,
        'app', 'src', 'main', 'res', 'xml'
      );

      fs.mkdirSync(target, { recursive: true });
      fs.writeFileSync(path.join(target, CONFIG_FILE), CONFIG_XML, 'utf8');

      return cfg;
    },
  ]);

/** Points <application> at it. */
const withManifestReference = (config) =>
  withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);

    application.$['android:networkSecurityConfig'] = `@xml/${CONFIG_FILE.replace('.xml', '')}`;

    return cfg;
  });

module.exports = (config) => withManifestReference(withConfigFile(config));
